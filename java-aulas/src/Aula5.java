public class Aula5 {
    public static void main(String[] args) {

        byte numero = -5;

        if (numero > 0) {
            System.out.println("Numero Possitivo");
        } else if (numero < 0) {
            System.out.println("Numero negaivo");
        } else if (numero == 0) {
            System.out.println("Zero");
        }

    }
}
